#!/bin/sh

# Hardware encode against a software encoder on the same source and bitrate.
#
# Every encode record in this tree compares the driver against itself, a
# sibling build or another hardware path. None of them answers the question a
# user actually asks: at this bitrate, how fast is it, and what does it cost
# the CPU? This gate runs the same synthetic source through the Iris encoder
# and through libx264/libx265 and reports both.
#
# What each cell is:
#   * frames per second of wall clock, from FFmpeg's own `bench:` line;
#   * client CPU seconds (utime + stime) per frame;
#   * the spread over the rounds, so a single noisy round is visible.
#
# The comparison is at equal bitrate, frame size, frame rate and GOP length.
# The encoders are not otherwise matched: the firmware decides its own
# partition and rate-control behaviour, libx264/libx265 run a named preset.
# A different preset moves the software arm and not the hardware one, which
# is why the preset is printed with every row.
#
# Usage:
#   test/target/iris-encode-baseline.sh [options]
#
# Options:
#   --size WxH        frame size (default 1920x1080)
#   --frames N        frames per round (default 300)
#   --rounds N        rounds per arm (default 3)
#   --bitrate B       target bitrate, e.g. 4M (default 4M at 1080p, 12M at 4K)
#   --preset P        software preset (default veryfast)
#   --codecs LIST     "h264 hevc" by default
#   --driver PATH     directory holding v4l2_drv_video.so (default
#                     <checkout>/build/src; name /usr/lib64/dri for the
#                     installed package)
#   --out DIR         artifact directory
#   --power           also measure device power per arm with
#                     test/target/iris-power-sampler.sh (needs the screen off and
#                     the tablet on battery)
#
# The source is testsrc2, generated by FFmpeg itself, so no media file is
# needed and both arms encode identical pixels.

set -eu

root=$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd)
. "$root/test/lib/iris-env.sh"

size=1920x1080
frames=300
rounds=3
bitrate=''
preset=veryfast
codecs='h264 hevc'
driver_path=${LIBVA_DRIVERS_PATH:-$root/build/src}
out=''
power=0
render=${IRIS_RENDER_NODE:-/dev/dri/renderD128}

while [ "$#" -gt 0 ]; do
    case $1 in
        --size) size=${2:?}; shift 2 ;;
        --frames) frames=${2:?}; shift 2 ;;
        --rounds) rounds=${2:?}; shift 2 ;;
        --bitrate) bitrate=${2:?}; shift 2 ;;
        --preset) preset=${2:?}; shift 2 ;;
        --codecs) codecs=${2:?}; shift 2 ;;
        --driver) driver_path=${2:?}; shift 2 ;;
        --out) out=${2:?}; shift 2 ;;
        --power) power=1; shift ;;
        -h|--help) sed -n '3,45p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "FAIL unknown argument: $1" >&2; exit 2 ;;
    esac
done

fail() {
    echo "FAIL encode-baseline: $*" >&2
    exit 1
}

[ -n "$bitrate" ] || case $size in
    3840x2160|7680x4320) bitrate=12M ;;
    *) bitrate=4M ;;
esac

case $size in
    [0-9]*x[0-9]*) ;;
    *) fail "--size must be WxH" ;;
esac
for n in "$frames" "$rounds"; do
    case $n in ''|*[!0-9]*) fail "frames and rounds must be positive integers" ;; esac
    [ "$n" -gt 0 ] || fail "frames and rounds must be positive integers"
done

command -v ffmpeg >/dev/null 2>&1 || fail 'ffmpeg is required'
[ -c "$render" ] || fail "not a DRM render node: $render"
[ -f "$driver_path/v4l2_drv_video.so" ] \
    || fail "no v4l2_drv_video.so in $driver_path; set --driver or LIBVA_DRIVERS_PATH"
[ -n "$out" ] || out=$(iris_artifact_dir encode-baseline)/$(date -u +%Y%m%dT%H%M%SZ)
mkdir -p "$out"

node=$(iris_resolve_encoder 2>/dev/null || true)
[ -n "$node" ] || fail 'no iris_driver encoder node found'
driver_sha=$(sha256sum "$driver_path/v4l2_drv_video.so" | cut -d' ' -f1)
boot_id=$(cat /proc/sys/kernel/random/boot_id)
governor=$(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor 2>/dev/null || echo unknown)

echo "encoder_node=$node render=$render driver=$driver_path sha256=$driver_sha"
echo "boot=$boot_id governor=$governor size=$size frames=$frames rounds=$rounds bitrate=$bitrate preset=$preset"

# One round: FFmpeg's own accounting. rtime is wall clock for the whole
# process, so fps is pictures per second of process time rather than a
# decoder-side estimate. CPU seconds come from utime + stime.
run_round() {
    arm=$1
    codec=$2
    log=$out/$codec-$arm.round.log
    if [ "$arm" = va ]; then
        LIBVA_DRIVER_NAME=v4l2 LIBVA_DRIVERS_PATH="$driver_path" \
            ffmpeg -hide_banner -benchmark -nostats -loglevel info \
            -vaapi_device "$render" \
            -f lavfi -i "testsrc2=size=$size:rate=30" -frames:v "$frames" \
            -vf format=nv12,hwupload -c:v "${codec}_vaapi" \
            -b:v "$bitrate" -g 60 -f null - >"$log" 2>&1 \
            || fail "$codec/$arm: encode failed (log $log)"
    else
        # FFmpeg names the software encoders libx264/libx265, not libh264.
        case $codec in h264) sw_codec=libx264 ;; hevc) sw_codec=libx265 ;; esac
        ffmpeg -hide_banner -benchmark -nostats -loglevel info \
            -f lavfi -i "testsrc2=size=$size:rate=30" -frames:v "$frames" \
            -c:v "$sw_codec" -preset "$preset" -b:v "$bitrate" -g 60 \
            -pix_fmt yuv420p -f null - >"$log" 2>&1 \
            || fail "$codec/$arm: encode failed (log $log)"
    fi
    bench=$(grep '^bench: utime=' "$log" | tail -1)
    [ -n "$bench" ] || fail "$codec/$arm: no bench line in $log"
    utime=$(printf '%s\n' "$bench" | sed -n 's/.*utime=\([0-9.]*\)s.*/\1/p')
    stime=$(printf '%s\n' "$bench" | sed -n 's/.*stime=\([0-9.]*\)s.*/\1/p')
    rtime=$(printf '%s\n' "$bench" | sed -n 's/.*rtime=\([0-9.]*\)s.*/\1/p')
    awk -v u="$utime" -v s="$stime" -v r="$rtime" -v f="$frames" \
        'BEGIN { if (r <= 0) exit 1; printf "%.1f %.4f\n", f / r, (u + s) / f }' \
        || fail "$codec/$arm: unusable bench line: $bench"
}

printf 'codec arm rounds fps_mean fps_min fps_max cpu_s_per_frame\n' >"$out/results.txt"
for codec in $codecs; do
    case $codec in h264|hevc) ;; *) fail "unsupported codec: $codec" ;; esac
    # A warm-up round: the first process pays for firmware boot and file
    # cache misses, and both are outside what the comparison measures.
    run_round va "$codec" >/dev/null
    run_round sw "$codec" >/dev/null
    for arm in va sw; do
        : >"$out/$codec-$arm.txt"
        i=0
        while [ "$i" -lt "$rounds" ]; do
            i=$((i + 1))
            run_round "$arm" "$codec" >>"$out/$codec-$arm.txt"
        done
        read -r fps_mean fps_min fps_max cpu <"$(awk '
            { f[NR] = $1; c[NR] = $2; s += $1; cs += $2 }
            END {
                lo = f[1]; hi = f[1]
                for (i = 1; i <= NR; i++) { if (f[i] < lo) lo = f[i]; if (f[i] > hi) hi = f[i] }
                printf "%s %s %s %s\n", s / NR, lo, hi, cs / NR
            }' "$out/$codec-$arm.txt" >"$out/$codec-$arm.summary" && echo "$out/$codec-$arm.summary")"
        printf '%s %s %s %s %s %s %s\n' "$codec" "$arm" "$rounds" \
            "$fps_mean" "$fps_min" "$fps_max" "$cpu" >>"$out/results.txt"
        echo "PASS $codec $arm fps=$fps_mean [$fps_min..$fps_max] cpu_s_per_frame=$cpu"
    done
done

awk 'NR == 1 { next }
    { fps[$1, $2] = $4; cpu[$1, $2] = $7; codecs[$1] = 1 }
    END {
        printf "%-6s %10s %10s %8s %14s %14s\n", "codec", "va_fps", "sw_fps", "speedup", "va_cpu_s/frame", "sw_cpu_s/frame"
        for (c in codecs) {
            ratio = fps[c, "sw"] > 0 ? fps[c, "va"] / fps[c, "sw"] : 0
            printf "%-6s %10.1f %10.1f %7.2fx %14.4f %14.4f\n", c, fps[c, "va"], fps[c, "sw"], ratio, cpu[c, "va"], cpu[c, "sw"]
        }
    }' "$out/results.txt" | tee "$out/summary.txt"

if [ "$power" = 1 ]; then
    for codec in $codecs; do
        echo "== power $codec"
        sh "$root/test/target/iris-power-sampler.sh" --workload encode --codec "$codec" \
            --size "$size" --bitrate "$bitrate" --preset "$preset" \
            --driver "$driver_path/v4l2_drv_video.so" \
            --out "$out/power-$codec" 2>&1 | tail -3
    done
fi

echo "PASS encode-baseline artifacts=$out"
